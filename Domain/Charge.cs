namespace AudioDirigent;

/// <summary>
/// Заряд и то, насколько точно он известен. Ступень важна не меньше числа: в объявлении
/// Bluetooth под заряд отведено четыре бита, туда помещаются только десятки, и 97 %
/// приезжают оттуда девяткой — ровно как приехали бы 90 %. Показать такое число как
/// точное значит соврать на девять процентов и заставить человека сверяться с телефоном.
/// </summary>
/// <param name="Step">Чем известно число: 1 — самим числом, 10 — с точностью до десятка.</param>
internal sealed record Charge(int Percent, int Step)
{
	/// <summary>Число известно как есть, а не с точностью до ступени.</summary>
	public bool Exact => Step <= 1;

	/// <summary>Как это писать человеку. Знак приблизительности — единственная честная разница.</summary>
	public string Text => Exact ? $"{Percent}%" : $"≈{Percent}%";
}
